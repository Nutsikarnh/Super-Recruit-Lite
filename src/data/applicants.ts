export type PipelineStage =
  | "new"
  | "shortlist"
  | "review"
  | "to_interview"
  | "interview"
  | "passed"
  | "offer"
  | "hired"
  | "rejected";

export interface Reviewer {
  name: string;
  email?: string;
  role: string;
  status: "pending" | "interested" | "not_sure";
  respondedAt?: string;
  comment?: string;
  availableTimes?: string[];
}

export interface ApplicantRow {
  id: string;
  name: string;
  initials: string;
  avatarColor: string;
  currentTitle: string;
  currentCompany: string;
  experience: string;
  education: string;
  location: string;
  salaryExpect: string;
  appliedAt: string;
  source: "direct" | "linkedin" | "jobsdb" | "refer";
  stage: PipelineStage;
  aiSummary: string;
  strengths: string[];
  concerns: string[];
  skills: string[];
  note?: string;
  isRead: boolean;

  // review workflow
  forwardedAt?: string;
  forwardedBy?: string;
  reviewers?: Reviewer[];
  preferredInterviewTimes?: string[];

  // to_interview workflow
  toInterviewMovedAt?: string;
  toInterviewSource?: string;
  toInterviewRecommendedInterviewers?: string[];

  // interview workflow
  interviewDate?: string;
  interviewDateIso?: string; // ISO datetime string for sorting/grouping e.g. "2026-05-03T10:00"
  interviewType?: string;
  interviewers?: string[];
  interviewEmailSent?: boolean;
  interviewNote?: string;

  // passed workflow
  passedAt?: string;
  passedBy?: string;
  passedComments?: string;
  passedNextStep?: string;

  // offer / hired
  offerAmount?: string;
  hiredAt?: string;
  hiredBy?: string;
  hiredStartDate?: string;
  hiredNote?: string;

  // rejected
  rejectionReason?: string;
  rejectedAt?: string;
  rejectedBy?: string;
  rejectionNote?: string;
}

